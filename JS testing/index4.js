function clear() {
    ctx.fillStyle = 'black';
    ctx.fillRect(0, 0, CW, CH);
}

function draw({ x, y, z }) {
    if (z > 0) {
        ctx.fillStyle = 'white';
        ctx.beginPath();
        ctx.arc(x, y, 3 / z, 0, 2 * Math.PI);
        ctx.fill();
    }
}

function screen({ x, y, z }) {
    return {
        x: (x + 1) * CW / 2,
        y: (1 - y) * CH / 2,
        z
    }
}

function project({ x, y, z }) {
    return {
        x: x / z,
        y: y / z,
        z
    }
}

function translate({ x, y, z }, dz) {
    return { x, y, z: z + dz };
}

function rotateX({ x, y, z }, angle) {
    const c = Math.cos(angle);
    const s = Math.sin(angle);
    return {
        x,
        y: c * y - s * z,
        z: s * y + c * z
    }
}

function rotateY({ x, y, z }, angle) {
    const c = Math.cos(angle);
    const s = Math.sin(angle);
    return {
        x: c * x - s * z,
        y,
        z: s * x + c * z
    }
}

function rotateZ({ x, y, z }, angle) {
    const c = Math.cos(angle);
    const s = Math.sin(angle);
    return {
        x: c * x - s * y,
        y: s * x + c * y,
        z
    }
}

function line(p1, p2) {
    if (p1.z > 0 && p2.z > 0) { //&& p1.x < CW && p1.x > 0 && p2.x < CW && p2.x > 0 && p1.y > 0 && p1.y < CH && p2.y > 0 && p2.y < CH) {
        ctx.strokeStyle = 'white';
        ctx.lineWidth = .25;
        ctx.beginPath();
        ctx.moveTo(p1.x, p1.y);
        ctx.lineTo(p2.x, p2.y);
        ctx.stroke();
    }
}

function drawTri(p1, p2, p3) {
    line(p1, p2);
    line(p2, p3);
    line(p3, p1);
}

function getRandomColor() {
    var letters = '0123456789ABCDEF';
    var color = '#';
    for (var i = 0; i < 6; i++) {
        color += letters[Math.floor(Math.random() * 16)];
    }
    return color;
}


function fillTri(p1, p2, p3, n) {
    ctx.fillStyle = colours[n];
    ctx.beginPath();
    ctx.moveTo(p1.x, p1.y);
    ctx.lineTo(p2.x, p2.y);
    ctx.lineTo(p3.x, p3.y);
    ctx.lineTo(p1.x, p1.y);
    ctx.closePath();
    ctx.fill();
    //ctx.stroke();
}

